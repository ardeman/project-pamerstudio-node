// Writes a promo video's YouTube text (title, description and every upload
// setting) from youtube.json, ready to paste. Called by lib.sh when it
// finishes a video:
//   node cobalagi/scripts/youtube-text.mjs <video> <out.txt>
// where <video> is the file name without .mp4 (promo-en, short-id, ...).
// The title carries the app's version name from its pubspec.yaml; STORE=live
// swaps "Coming soon" for the Google Play link.
//   node cobalagi/scripts/youtube-text.mjs --check
// checks every video's text against YouTube's limits, without writing.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { app } from './app.mjs'

// YouTube's limits.
const titleLimit = 100
const descriptionLimit = 5000

const copy = JSON.parse(readFileSync(new URL('youtube.json', import.meta.url), 'utf8'))

// The version name in pubspec.yaml, e.g. 2.1.0 from `version: 2.1.0+15`.
function appVersion() {
  const match = /^version:\s*([^+\s]+)/m.exec(readFileSync(resolve(app, 'pubspec.yaml'), 'utf8'))
  if (!match) throw new Error('No version in pubspec.yaml')
  return match[1]
}

function entry(video) {
  const found = copy.videos[video]
  if (!found) throw new Error(`No YouTube text for ${video}`)
  return found
}

const langOf = (video) => video.split('-').at(-1)

function titleOf(video, version) {
  const raw = entry(video).title
  if (!raw.includes('{version}')) throw new Error(`The title of ${video} must include {version}`)
  return raw.replaceAll('{version}', version)
}

function descriptionOf(video, live) {
  return entry(video).description.replaceAll('{store}', copy.store[live ? 'live' : 'soon'][langOf(video)])
}

function youtubeText(video, { version, live }) {
  const kind = video.split('-')[0] // promo or short
  const fill = (text) => text
    .replaceAll('{lang}', langOf(video))
    .replaceAll('{video}', video)
    .replaceAll('{language}', entry(video).language)
    .replaceAll('{tags}', copy.tags)
  let settings = ''
  for (const row of copy.settings) {
    const choice = row[kind] ?? row.all
    if (choice == null) continue
    settings += `- ${row.setting}: ${fill(choice)}\n`
    // A reason is one text, or one per kind of video.
    const why = typeof row.why === 'string' ? row.why : row.why?.[kind]
    if (why != null) settings += `  (${fill(why)})\n`
  }
  return `${video}.mp4 · Coba Lagi ${version} · ${live ? 'on Google Play' : 'coming soon'}
Generated by cobalagi/scripts/youtube-text.mjs from youtube.json; don't edit.
YouTube can't replace a video's file: to update one, delete it and upload
the new one.

TITLE
${titleOf(video, version)}

DESCRIPTION
${descriptionOf(video, live)}

SETTINGS
${settings}`
}

// What YouTube refuses or would show unfilled, for every video either way.
function check(version) {
  const problems = []
  const expected = ['promo-en', 'promo-id', 'short-en', 'short-id']
  const videos = Object.keys(copy.videos)
  if (videos.sort().join() !== expected.join()) problems.push(`videos are ${videos}, expected ${expected}`)
  for (const video of videos) {
    const title = titleOf(video, version)
    if (!title.includes(`Coba Lagi ${version}`)) problems.push(`${video}: title lacks "Coba Lagi ${version}"`)
    if (title.length > titleLimit) problems.push(`${video}: title is ${title.length} characters (max ${titleLimit})`)
    if (/[<>]/.test(title)) problems.push(`${video}: title has angle brackets`)
    for (const live of [false, true]) {
      const description = descriptionOf(video, live)
      const which = live ? 'live' : 'soon'
      if (description.length > descriptionLimit) problems.push(`${video} (${which}): description is ${description.length} characters (max ${descriptionLimit})`)
      if (description.includes('{')) problems.push(`${video} (${which}): description has an unfilled {…}`)
      if (/[<>]/.test(description)) problems.push(`${video} (${which}): description has angle brackets`)
      // The store link only once the app is public.
      if (description.includes('play.google.com') !== live) problems.push(`${video} (${which}): store link ${live ? 'missing' : 'too early'}`)
    }
    const text = youtubeText(video, { version, live: false })
    if (text.includes('{')) problems.push(`${video}: settings have an unfilled {…}`)
    if (!text.includes(`${video}.srt`)) problems.push(`${video}: settings don't name ${video}.srt`)
  }
  return problems
}

const args = process.argv.slice(2)
const version = appVersion()
const problems = check(version)
if (problems.length) {
  console.error(problems.join('\n'))
  process.exit(1)
}
if (args[0] === '--check') {
  console.log(`YouTube text OK for Coba Lagi ${version}`)
} else if (args.length === 2) {
  writeFileSync(args[1], youtubeText(args[0], { version, live: process.env.STORE === 'live' }))
} else {
  console.error('Usage: node cobalagi/scripts/youtube-text.mjs <video> <out.txt> | --check')
  process.exit(64)
}
